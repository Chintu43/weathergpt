import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import dotenv from 'dotenv';
import bcrypt from 'bcryptjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const backendDir = path.resolve(__dirname, '..');
const envPath = path.join(backendDir, '.env');

dotenv.config({ path: envPath });

import { getUserByEmail, updateUserPassword } from '../src/services/supabaseService.js';
import { passwordStore } from '../src/services/passwordStore.js';

/**
 * WeatherGPT Secure Admin Password Reset Utility
 *
 * Usage:
 *   node scripts/resetAdminPassword.js [newPassword] [adminEmail]
 *
 * If newPassword is not provided, a strong 16-character random password is generated.
 * Default admin email: prudhviisa4@gmail.com
 */
async function resetAdminPassword() {
  const targetEmail = (process.argv[3] || process.env.ADMIN_EMAIL || 'prudhviisa4@gmail.com').trim().toLowerCase();
  let newPassword = process.argv[2];

  let isAutoGenerated = false;
  if (!newPassword || !newPassword.trim()) {
    isAutoGenerated = true;
    newPassword = crypto.randomBytes(12).toString('base64').replace(/[^a-zA-Z0-9]/g, '').slice(0, 16) + '!A9';
  } else {
    newPassword = newPassword.trim();
  }

  if (newPassword.length < 6) {
    console.error('[Error] Password must be at least 6 characters long.');
    process.exit(1);
  }

  console.log('====================================================');
  console.log(' WeatherGPT Secure Administrator Password Reset');
  console.log('====================================================');
  console.log(`Target Admin Email: ${targetEmail}`);

  // 1. Verify that user exists in database and has role 'admin'
  let user;
  try {
    user = await getUserByEmail(targetEmail);
  } catch (err) {
    console.error(`[Error] Database error looking up user ${targetEmail}:`, err.message);
    process.exit(1);
  }

  if (!user) {
    console.error(`[Error] User "${targetEmail}" was not found in Supabase public.users.`);
    process.exit(1);
  }

  if (user.role !== 'admin') {
    console.error(`[Error] Security refusal: User "${targetEmail}" has role "${user.role}", not "admin".`);
    console.error('This script only resets administrator accounts to prevent accidental privilege escalation.');
    process.exit(1);
  }

  console.log(`[Verified] Account found in Supabase public.users with role: "${user.role}".`);
  console.log(`[Hashing] Generating bcrypt hash (salt rounds: 10)...`);

  const passwordHash = await bcrypt.hash(newPassword, 10);

  // 2. Update Supabase public.users.password_hash (authoritative database store)
  console.log(`[Database] Updating password_hash in Supabase public.users...`);
  try {
    const updatedUser = await updateUserPassword(targetEmail, passwordHash);
    console.log(`[Database] Successfully updated Supabase password_hash.`);
    console.log(`[Database] Verified role preserved: "${updatedUser.role}".`);
  } catch (err) {
    console.error(`[Error] Failed to update password in Supabase:`, err.message);
    process.exit(1);
  }

  // 3. Update backend/.env ADMIN_PASSWORD_HASH for environment synchronization
  if (fs.existsSync(envPath)) {
    try {
      let envContent = fs.readFileSync(envPath, 'utf-8');
      if (envContent.includes('ADMIN_PASSWORD_HASH=')) {
        envContent = envContent.replace(/^ADMIN_PASSWORD_HASH=.*$/m, `ADMIN_PASSWORD_HASH=${passwordHash}`);
      } else {
        envContent += `\nADMIN_PASSWORD_HASH=${passwordHash}\n`;
      }
      fs.writeFileSync(envPath, envContent, 'utf-8');
      console.log(`[Environment] Updated ADMIN_PASSWORD_HASH in backend/.env.`);
    } catch (envErr) {
      console.warn(`[Warning] Could not update backend/.env:`, envErr.message);
    }
  }

  // 4. Update legacy passwordStore (backend/data/passwords.json)
  try {
    passwordStore.set(targetEmail, passwordHash);
    console.log(`[Legacy Store] Updated backend/data/passwords.json.`);
  } catch (storeErr) {
    console.warn(`[Warning] Could not update local passwordStore:`, storeErr.message);
  }

  // 5. Verification Test
  const verifiedUser = await getUserByEmail(targetEmail);
  const isValid = await bcrypt.compare(newPassword, verifiedUser.password);

  if (!isValid) {
    console.error(`[Error] Verification failed: freshly generated hash does not validate against new password.`);
    process.exit(1);
  }

  console.log('====================================================');
  console.log(' SUCCESS: Admin password has been securely reset!');
  console.log('====================================================');
  console.log(`Admin Email: ${targetEmail}`);
  console.log(`Role: ${verifiedUser.role}`);
  console.log(`Updated At: ${verifiedUser.updated_at || new Date().toISOString()}`);
  if (isAutoGenerated) {
    console.log(`Generated Password: ${newPassword}`);
    console.log('Please save this password securely.');
  } else {
    console.log('Custom password applied successfully.');
  }
  console.log('====================================================\n');
}

resetAdminPassword().catch((err) => {
  console.error('[Fatal Error]:', err);
  process.exit(1);
});
